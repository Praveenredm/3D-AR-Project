  /// Categories within a domain that actually have at least one quiz question.
  static List<String> quizCategoriesForDomain(String domainId) {
    final categories = quizQuestions
        .where((q) => q.domainId == domainId)
        .map((q) => q.category)
        .toSet()
        .toList();
    categories.sort();
    return categories;
  }

  /// Filtered + shuffled question pool for a domain/category combo.
  /// Pass category == 'All' to include every category in that domain.
  static List<QuizQuestion> quizQuestionsFor({
    required String domainId,
    required String category,
  }) {
    final pool = quizQuestions.where((q) {
      final domainMatch = q.domainId == domainId;
      final categoryMatch = category == 'All' || q.category == category;
      return domainMatch && categoryMatch;
    }).toList();

    pool.shuffle();
    return pool;
  }

  /// Total questions available for a domain/category, so the setup screen
  /// can disable count options that exceed the available pool.
  static int quizQuestionCountFor({
    required String domainId,
    required String category,
  }) {
    return quizQuestionsFor(domainId: domainId, category: category).length;
  }
