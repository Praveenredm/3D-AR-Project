    if (_modelsMap.containsKey(id)) {
      return _modelsMap[id]!;
    }
    // Search in topics to build dynamic model if not pre-registered
    for (final domain in domains) {
      final topics = getTopics(domain.id);
      for (final topic in topics) {
        if (topic.id == id || topic.modelId == id) {
          return ModelItem(
            id: topic.id,
            title: topic.title,
            subtitle: topic.subtitle,
            domainId: topic.domainId,
            category: topic.category,
            description:
                '${topic.title} is an essential component of the ${domain.title.replaceAll('\n', ' ')} domain.',
            keyFacts: {
              'Domain': domain.title.replaceAll('\n', ' '),
