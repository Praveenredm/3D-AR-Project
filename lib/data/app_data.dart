  // Helper method to get the model associated with a topic item
  static ModelItem getModelForTopic(TopicItem topic) {
    final targetId = topic.modelId ?? topic.id;
    return getModelById(targetId);
  }

  // Global search across all models and topics in all 6 domains
  static List<TopicItem> searchAllTopics(String query) {
    final q = query.toLowerCase().trim();
    if (q.isEmpty) return const [];

    final List<TopicItem> results = [];
    for (final domain in domains) {
      final topics = getTopics(domain.id);
      for (final topic in topics) {
        if (topic.title.toLowerCase().contains(q) ||
            topic.subtitle.toLowerCase().contains(q) ||
            topic.category.toLowerCase().contains(q)) {
          results.add(topic);
        }
      }
    }
    return results;
  }

